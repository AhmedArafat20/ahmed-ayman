/* Scans img/projects and writes js/images.js so the site shows ONLY projects that have an image.
   Run:  npm run manifest   (or double-click update-images.bat)   -- runs automatically after npm run shots */
const fs = require("fs"), path = require("path");
function run() {
  const root = path.join(__dirname, ".."), dir = path.join(root, "img/projects"), found = {};
  for (const f of fs.existsSync(dir) ? fs.readdirSync(dir) : []) {
    const x = f.match(/^(.+)\.(jpe?g|png|webp)$/i); if (x) found[x[1].toLowerCase()] = x[2].toLowerCase();
  }
  fs.writeFileSync(path.join(root, "js/images.js"), "/* generated by tools/manifest.js (run: npm run manifest). Empty = show every project. */\nconst HAS_IMG = " + JSON.stringify(found, null, 1) + ";\n");
  console.log("Projects with images: " + Object.keys(found).length + "  ->  js/images.js updated");
}
module.exports = { run };
if (require.main === module) run();
